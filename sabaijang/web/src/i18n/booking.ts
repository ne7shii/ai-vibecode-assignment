/** fill('ห้องที่ {n}', { n: 2 }) → 'ห้องที่ 2' */
export function fill(s: string, vars: Record<string, string | number>): string {
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}
